// Function to populate apps table with filters
function fetchApps() {
  try {
    const tbody = document.getElementById('apps-list');
    tbody.innerHTML = '';
    const storeFilter = document.getElementById('store-filter').value;
    const categoryFilter = document.getElementById('category-filter').value;
    const ratingFilter = document.getElementById('rating-filter').value;
    const priceFilter = document.getElementById('price-filter').value;
    const searchQuery = document.getElementById('search-input').value.toLowerCase();

    let filteredApps = allApps;

    // Apply store filter
    if (storeFilter !== 'both') {
      filteredApps = filteredApps.filter(app => app.store === storeFilter);
    }

    // Apply category filter
    if (categoryFilter !== 'all') {
      filteredApps = filteredApps.filter(app => app.category && app.category.toLowerCase() === categoryFilter);
    }

    // Apply rating filter
    if (ratingFilter !== 'all') {
      const minRating = parseFloat(ratingFilter);
      filteredApps = filteredApps.filter(app => app.rating !== 'N/A' && parseFloat(app.rating) >= minRating);
    }

    // Apply price filter
    if (priceFilter !== 'all') {
      filteredApps = filteredApps.filter(app => app.price && app.price.toLowerCase() === priceFilter);
    }

    // Apply search filter
    if (searchQuery) {
      filteredApps = filteredApps.filter(app =>
        app.title.toLowerCase().includes(searchQuery) ||
        app.developer.toLowerCase().includes(searchQuery)
      );
    }

    // Sort by rank and limit to 100
    filteredApps = filteredApps.sort((a, b) => a.rank - b.rank).slice(0, 100);

    // Ensure minimum 50 entries per category
    const categoryCounts = {};
    filteredApps.forEach(app => {
      if (app.category) {
        categoryCounts[app.category] = (categoryCounts[app.category] || 0) + 1;
      }
    });

    // Log warnings for categories with fewer than 50 entries
    Object.keys(categoryCounts).forEach(category => {
      if (categoryCounts[category] < 50) {
        console.warn(`Category ${category} has only ${categoryCounts[category]} entries, which is less than the required 50.`);
      }
    });

    // Populate table
    filteredApps.forEach(app => {
      const row = document.createElement('tr');
      row.innerHTML = `
        <td><a href="${app.download_link}" target="_blank">${app.title}</a></td>
        <td>${app.developer}</td>
        <td>${app.category || 'N/A'}</td>
        <td>${app.rating}</td>
        <td>${app.reviews}</td>
<td>${app.store}</td>
      `;
      tbody.appendChild(row);
    });

    // If no apps match filters, display message
    if (filteredApps.length === 0) {
      tbody.innerHTML = '<tr><td colspan="9" class="error-msg">No apps match the selected filters.</td></tr>';
    }
  } catch (error) {
    console.error('Error rendering apps:', error);
    document.getElementById('apps-list').innerHTML = '<tr><td colspan="9" class="error-msg">Failed to load apps.</td></tr>';
  }
}

